# порядок проверки при совпадении сразу нескольких наборов
PRIORITY = ["delo", "telo", "privychka", "ucheba", "dom", "lyubov",
            "tvorchestvo", "karera", "dengi", "pokoy"]

# то, что показывается кнопками на первом экране — по одному слову
DIRECTIONS = [
    {"key": k, "label": v["label"], "example": v["example"], "vision": v["example_vision"]}
    for k, v in PACKS.items()
]


def clean(pack: dict) -> dict:
    return {k: v for k, v in pack.items()
            if k not in ("keywords", "label", "example", "example_vision")}


def pack_by_key(key: str) -> dict | None:
    """Набор по выбранному направлению."""
    return clean(PACKS[key]) if key in PACKS else None


def match_pack(goal: str, vision: str = "") -> dict | None:
    """Запасной подбор по словам цели, если направление не выбрано.
    Слова из самой цели весят вдвое больше, чем из описания."""
    def norm(t):
        return (t or "").lower().replace("ё", "е")

    g, v = norm(goal), norm(vision)
    scores = {}
    for key, pack in PACKS.items():
        hits = sum(2 for w in pack["keywords"] if norm(w) in g)
        hits += sum(1 for w in pack["keywords"] if norm(w) in v)
        if hits:
            scores[key] = hits
    if not scores:
        return None
    best = max(scores.values())
    for key in PRIORITY:
        if scores.get(key) == best:
            return clean(PACKS[key])
    return None
